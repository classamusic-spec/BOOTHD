/// Occasion metadata shared by the template chooser and sticker browser.
/// Artwork is bundled; every title, caption and photo window stays editable.
library;

final class OccasionTheme {
  const OccasionTheme({
    required this.key,
    required this.name,
    required this.collection,
    required this.title,
    required this.subtitle,
    required this.paper,
    required this.ink,
    required this.accent,
    required this.tags,
    this.hero = false,
  });

  final String key;
  final String name;
  final String collection;
  final String title;
  final String subtitle;
  final int paper;
  final int ink;
  final int accent;
  final List<String> tags;
  final bool hero;

  String get stickerId => 'sticker_$key';
  String get designId => 'occasion_$key';
}

